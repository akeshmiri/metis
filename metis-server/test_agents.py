def test_no_agent_surface_carries_a_file_no_skill_produces():
    """The rot this closes was real and invisible to both existing tests.

    `plugins/metis/agents/` held four agents for skills that had been deleted,
    naming twelve MCP tools the server does not expose, and linking to a
    `metis-onboarding/SKILL.md` that no longer exists. `test_skills.py` scans
    `skills/` and the router; this file scanned `.github/agents/`. The plugin's
    own agent directory was a third surface, generated by nothing and checked by
    nothing — while every file in it carried a "GENERATED … do not hand-edit"
    banner.
    """
    for target in AGENT_TARGETS:
        assert stale_agents(target) == [], (
            f"{target} carries agent file(s) no live skill produces: "
            f"{[p.name for p in stale_agents(target)]}. Regenerate with "
            f"agent_generator.write()")


def test_there_is_exactly_one_agent_surface():
    """**This replaces two tests that existed only because there were two.**

    `.github/agents/` and `plugins/metis/agents/` held byte-identical files, so
    every agent was in the repository twice and two guards were needed to assert
    the copies agreed. Agents ship through the marketplace plugin now, which
    makes the plugin the one place they live — and a duplicate cannot disagree
    with itself if it does not exist.
    """
    assert AGENT_TARGETS == (PLUGIN_AGENTS,), (
        "a second agent surface is back — it will be regenerated out of step "
        "with this one, which is what the duplication cost last time")
    assert not (PLUGIN_AGENTS.parent.parent.parent / ".github" / "agents").exists(), (
        ".github/agents/ is back and duplicates the plugin surface")


def test_the_generated_agents_match_the_generator_exactly():
    """One generator, one content, one place."""
    for filename, content in generate().items():
        assert (PLUGIN_AGENTS / filename).read_text() == content, (
            f"{filename} has drifted from the generator")


